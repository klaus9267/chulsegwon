package reach

/** [startSec, endSec) 구간의 배차간격. 자정 넘는 막차는 86400 을 넘는 값으로 표현한다. */
class ServicePeriod(val startSec: Int, val endSec: Int, val headwaySec: Int)

/**
 * ⚠️ 추정치다. 실제 시간표가 아니다.
 *
 * ✅ **1~9호선은 이제 여기를 안 쓴다.** 서울교통공사 실측 시각표가 대신한다
 * ([RailTimetable], ADR-38). 합성이 노선마다 배차 하나를 주는 방식이 강남 2호선을
 * 78%, 수원 1호선을 93% 과잉 운행시키고 있었다.
 *
 * 아직 여기에 매달린 것: 경의중앙·수인분당·경춘·신분당·공항철도·서해·인천1·2·
 * 의정부·에버라인·우이신설·김포골드·경강 13개 노선. 코레일 광역철도 시각표는
 * 공개 파일로 안 나온다 — 찾아봤고, 예매 시스템 안에만 있다.
 */
object Headways {
    private fun hm(h: Int, m: Int) = h * 3600 + m * 60

    // 20~23시를 7분으로 뒀다가 카카오맵 대조에서 첫 승차 대기가 일관되게 과하게 나와
    // 5분으로 낮췄다. 표본에 맞춘 게 아니라 실제 저녁 배차(2호선 기준 4~5분)에 맞춘 것이다.
    val WEEKDAY = listOf(
        ServicePeriod(hm(5, 30), hm(7, 0), 6 * 60),
        ServicePeriod(hm(7, 0), hm(9, 0), 3 * 60),    // 출근 피크
        ServicePeriod(hm(9, 0), hm(17, 0), 6 * 60),
        ServicePeriod(hm(17, 0), hm(20, 0), 4 * 60),  // 퇴근 피크
        ServicePeriod(hm(20, 0), hm(23, 0), 5 * 60),
        ServicePeriod(hm(23, 0), hm(24, 40), 10 * 60), // 막차
    )

    /**
     * 광역철도는 배차가 길다. 기본 1.0 에 노선별 배율.
     *
     * ⚠️ **GTX-A 를 빼먹으면 안 된다.** 2026-09 에 OSM 으로 망을 갈아끼우면서
     * 새 노선이 들어왔는데([RailOsm]) 배율이 없어 기본 1.0 이 붙었다. 그러면
     * 저녁 배차가 4분이 되는데 **실제는 17~20분**이다 — 운정중앙·동탄·구성처럼
     * GTX 로만 닿는 동네가 통째로 4배 가까워 보인다. 새 노선을 넣을 때는 여기도
     * 같이 봐야 한다.
     */
    private val LINE_MULTIPLIER = mapOf(
        "경의중앙" to 2.5, "경춘" to 3.0, "수인분당" to 1.6, "경강" to 2.5,
        "서해" to 2.2, "공항철도" to 1.8, "인천1" to 1.3, "인천2" to 1.3,
        "의정부" to 1.3, "용인" to 1.3, "우이신설" to 1.3, "김포" to 1.2,
        // 2026-09 추가분
        "GTX" to 3.5,          // 실제 17~20분. 기본 4분에 3.5 배 = 14분(계통당)
        "신분당" to 1.4,        // 실제 6~8분
        "신림" to 1.2,          // 실제 5~6분
    )

    fun multiplierFor(line: String): Double =
        LINE_MULTIPLIER.entries.firstOrNull { line.contains(it.key) }?.value ?: 1.0

    /**
     * 역 하나를 지나는 데 붙는 시간(초).
     *
     * **처음엔 0 이었고, 그게 틀렸다.** 카카오맵 지하철 구간 206개와 대보니
     * 우리 승차시간이 일관되게 8.8% 짧았다(편향 −95초). 아래 표정속도는 구간을
     * 달리는 속도지 감속·정차·가속을 담지 않는다.
     *
     * OD 40개를 반으로 갈라 한쪽으로 맞추고 다른 쪽으로 평가했다:
     * 평가셋 편향 −113초 → −18초 · MAE 133초 → 82초 · ±3분 이내 78% → 90%.
     *
     * ⚠️ 이 값을 바꾸면 **문앞-문앞 대조(−0.9분)도 다시 재야 한다.** 그 검증은
     * 승차시간이 짧은 것과 대기시간이 긴 것이 상쇄돼 맞아 보였던 것이라
     * (ADR-29 의 반박 검증), 한쪽만 고치면 총합이 오히려 어긋난다.
     */
    private const val STATION_DWELL_SEC = 10

    /**
     * 표정속도 기반 구간 소요시간 + 역 통과 비용.
     * 도심 지하철은 역간이 짧고 느리며, 광역철도는 역간이 길고 빠르다.
     */
    fun segmentSeconds(meters: Double): Int {
        val kmh = if (meters < 1_500) 32.0 else 50.0
        return (meters / (kmh * 1000.0 / 3600.0)).toInt().coerceAtLeast(30) + STATION_DWELL_SEC
    }
}
